// ABOUTME: Generates docs/palette.md - a light+dark swatch reference for the Obol design tokens.
// ABOUTME: Parses the --obol-* values out of assets/styles/app.css so the page never drifts from
// ABOUTME: the source of truth. Run via `mise run palette` after editing the palette; output is committed.

import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const cssPath = join(root, 'assets/styles/app.css');
const outPath = join(root, 'docs/palette.md');

// Pull the var declarations out of a single CSS rule block (no nested braces in these blocks).
function parseBlock(css, selector) {
  const re = new RegExp(`${selector}\\s*\\{([^}]*)\\}`);
  const body = css.match(re)?.[1] ?? '';
  const vars = {};
  for (const [, name, value] of body.matchAll(/--obol-([\w-]+):\s*(#[0-9a-fA-F]{3,8});/g)) {
    vars[name] = value.toLowerCase();
  }
  return vars;
}

// Presentation metadata only - the color values come from app.css, never from here. Each row names
// the token and the Tailwind utility it generates (via the @theme inline mapping). Grouped by role.
const groups = [
  {
    title: 'Surfaces',
    blurb: 'Page and card backgrounds.',
    tokens: [
      ['page', 'bg-page'],
      ['surface', 'bg-surface'],
      ['surface-2', 'bg-surface-2'],
    ],
  },
  {
    title: 'Text',
    blurb: 'Foreground text on the surfaces above.',
    tokens: [
      ['fg', 'text-fg'],
      ['fg-muted', 'text-fg-muted'],
    ],
  },
  {
    title: 'Brand (logo gold)',
    blurb: 'The single accent, drawn from the heraldic gold coin.',
    tokens: [
      ['brand', 'bg-brand / text-brand'],
      ['brand-strong', 'text-brand-strong'],
      ['on-brand', 'text-on-brand'],
    ],
  },
  {
    title: 'Lines',
    blurb: 'Borders and dividers.',
    tokens: [
      ['line', 'border-line / divide-line'],
      ['line-strong', 'border-line-strong'],
    ],
  },
  {
    title: 'Header band',
    blurb: 'The deep coin-brown nav band; its text stays light in both schemes.',
    tokens: [
      ['header', 'bg-header'],
      ['header-fg', 'text-header-fg'],
      ['header-muted', 'text-header-muted'],
    ],
  },
  {
    title: 'State colors',
    blurb: 'Status accents, each paired with a tinted surface for backgrounds.',
    tokens: [
      ['success', 'text-success / bg-success'],
      ['success-surface', 'bg-success-surface'],
      ['warning', 'text-warning / bg-warning'],
      ['warning-surface', 'bg-warning-surface'],
      ['danger', 'text-danger / bg-danger'],
      ['danger-surface', 'bg-danger-surface'],
      ['info', 'text-info / bg-info'],
      ['info-surface', 'bg-info-surface'],
    ],
  },
];

function swatch(hex, panel) {
  // The page itself is not themed by app.css, so each swatch sits in a literal panel matching
  // its scheme and carries a ring so near-page-colored tokens stay visible.
  const cellBg = panel === 'light' ? '#f3ecdb' : '#14100a';
  const cellFg = panel === 'light' ? '#2a2012' : '#f5ecd8';
  return (
    `<td style="background:${cellBg};color:${cellFg};white-space:nowrap">` +
    `<span style="display:inline-block;width:1.4rem;height:1.4rem;border-radius:4px;` +
    `vertical-align:middle;background:${hex};box-shadow:inset 0 0 0 1px rgba(128,128,128,.5)"></span> ` +
    `<code style="background:transparent;color:inherit">${hex}</code></td>`
  );
}

function table(group, light, dark) {
  const rows = group.tokens
    .filter(([name]) => name in light)
    .map(([name, utility]) => {
      const lightHex = light[name];
      const darkHex = dark[name] ?? light[name]; // shared tokens keep their light value in dark
      return (
        '<tr>' +
        `<td><code>--obol-${name}</code></td>` +
        `<td><code>${utility}</code></td>` +
        swatch(lightHex, 'light') +
        swatch(darkHex, 'dark') +
        '</tr>'
      );
    })
    .join('\n');
  return (
    `### ${group.title}\n\n${group.blurb}\n\n` +
    '<table>\n<thead><tr><th>Token</th><th>Utility</th><th>Light</th><th>Dark</th></tr></thead>\n' +
    `<tbody>\n${rows}\n</tbody>\n</table>\n`
  );
}

const css = await readFile(cssPath, 'utf8');
const light = parseBlock(css, ':root');
const dark = parseBlock(css, '\\.dark');

// Surface any parsed token that no group claims, so a future token is never silently dropped.
const claimed = new Set(groups.flatMap((g) => g.tokens.map(([n]) => n)));
const orphans = Object.keys(light).filter((n) => !claimed.has(n));
if (orphans.length > 0) {
  groups.push({
    title: 'Ungrouped',
    blurb: 'Tokens not yet assigned a role in the generator - add them to a group in bin/generate-palette-doc.mjs.',
    tokens: orphans.map((n) => [n, '-']),
  });
}

const body =
  '<!-- Generated by `mise run palette` from assets/styles/app.css. Do not edit by hand. -->\n\n' +
  '# Palette reference\n\n' +
  'Every Obol design token as a light and dark swatch. These are the semantic tokens defined on\n' +
  '`:root` (light) and `.dark` (dark) in `assets/styles/app.css` and exposed to Tailwind via\n' +
  '`@theme inline`, so each one drives the named utility shown alongside it.\n\n' +
  '!!! note "Generated, not hand-maintained"\n' +
  '    This page is produced by `mise run palette`, which reads the values straight out of\n' +
  '    `assets/styles/app.css`. After changing the palette, re-run it and commit the refreshed\n' +
  '    page - never edit the swatches here by hand. See [Frontend](frontend.md) for how the\n' +
  '    tokens are wired.\n\n' +
  groups.map((g) => table(g, light, dark)).join('\n') +
  '\n';

await writeFile(outPath, body);
const total = groups.reduce((n, g) => n + g.tokens.filter(([t]) => t in light).length, 0);
console.log(`Wrote docs/palette.md (${total} tokens across ${groups.length} groups).`);
